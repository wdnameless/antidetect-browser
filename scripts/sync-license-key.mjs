#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const pemPath = path.join(rootDir, 'resources', 'license-public-key.pem');
const outPath = path.join(rootDir, 'src', 'main', 'licensing', 'publicKey.ts');

if (!fs.existsSync(pemPath)) {
  console.error(`Error: PEM file not found at ${pemPath}`);
  process.exit(1);
}

// CRITICAL: byte-for-byte exact embedding as in file, including trailing newline
const pemContent = fs.readFileSync(pemPath, 'utf8');

const tsContent = `// Auto-generated by scripts/sync-license-key.mjs — DO NOT EDIT MANUALLY.
// Pinned Ed25519 public key for offline license validation.
// The matching PRIVATE KEY is NEVER committed.
// Run 'node scripts/sync-license-key.mjs' after rotating resources/license-public-key.pem.

export const LICENSE_PUBLIC_KEY_PEM = ${JSON.stringify(pemContent)};
`;

fs.writeFileSync(outPath, tsContent, 'utf8');
console.log(`Successfully synced license public key to ${outPath}`);
